// ident renders an Oak identifier as a Lean identifier: Lean keywords and
// the names the translation itself uses get a trailing underscore.
func ident(name string) string {
	if leanReserved[name] {
		return name + "_"
	}
	return name
}

func identAll(names []string) []string {
	out := make([]string, len(names))
	for i, name := range names {
		out[i] = ident(name)
	}
	return out
}

