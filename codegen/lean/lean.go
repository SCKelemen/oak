// walkStatements visits every statement nested in an expression.
func walkStatements(expr ast.Expression, visit func(ast.Statement)) {
	var stmts func(list []ast.Statement)
	var exprs func(e ast.Expression)
	stmts = func(list []ast.Statement) {
		for _, stmt := range list {
			visit(stmt)
			switch s := stmt.(type) {
			case *ast.VariableDeclaration:
				exprs(s.Value)
			case *ast.AssignmentStatement:
				exprs(s.Value)
			case *ast.IndexAssignmentStatement:
				exprs(s.Value)
			case *ast.WhileStatement:
				exprs(s.Condition)
				if s.Body != nil {
					stmts(s.Body.Statements)
				}
			case *ast.ExpressionStatement:
				exprs(s.Expression)
			case *ast.BlockStatement:
				stmts(s.Statements)
			}
		}
	}
	exprs = func(e ast.Expression) {
		switch x := e.(type) {
		case *ast.BlockExpression:
			if x.Block != nil {
				stmts(x.Block.Statements)
			}
		case *ast.MatchExpression:
			exprs(x.Scrutinee)
			for _, arm := range x.Arms {
				exprs(arm.Body)
			}
		case *ast.InfixExpression:
			exprs(x.Left)
			exprs(x.Right)
		case *ast.PrefixExpression:
			exprs(x.Right)
		case *ast.InvocationExpression:
			for _, arg := range x.Arguments {
				exprs(arg)
			}
		case *ast.ArrayLiteral:
			for _, element := range x.Elements {
				exprs(element)
			}
		case *ast.RecordLiteral:
			for _, field := range x.FieldOrder {
				exprs(field.Value)
			}
		case *ast.VariantExpression:
			exprs(x.Payload)
		}
	}
	exprs(expr)
}

// walkExpressions visits every expression nested in an expression,
// including those inside nested statements.
func walkExpressions(expr ast.Expression, visit func(ast.Expression)) {
	var stmts func(list []ast.Statement)
	var exprs func(e ast.Expression)
	stmts = func(list []ast.Statement) {
		for _, stmt := range list {
			switch s := stmt.(type) {
			case *ast.VariableDeclaration:
				exprs(s.Value)
			case *ast.AssignmentStatement:
				exprs(s.Value)
			case *ast.IndexAssignmentStatement:
				exprs(s.Target)
				exprs(s.Value)
			case *ast.WhileStatement:
				exprs(s.Condition)
				if s.Body != nil {
					stmts(s.Body.Statements)
				}
			case *ast.ExpressionStatement:
				exprs(s.Expression)
			case *ast.BlockStatement:
				stmts(s.Statements)
			}
		}
	}
	exprs = func(e ast.Expression) {
		if e == nil {
			return
		}
		visit(e)
		switch x := e.(type) {
		case *ast.BlockExpression:
			if x.Block != nil {
				stmts(x.Block.Statements)
			}
		case *ast.MatchExpression:
			exprs(x.Scrutinee)
			for _, arm := range x.Arms {
				exprs(arm.Body)
			}
		case *ast.InfixExpression:
			exprs(x.Left)
			exprs(x.Right)
		case *ast.PrefixExpression:
			exprs(x.Right)
		case *ast.InvocationExpression:
			exprs(x.Function)
			for _, arg := range x.Arguments {
				exprs(arg)
			}
		case *ast.IndexExpression:
			exprs(x.Left)
			if !x.Dot {
				exprs(x.Index)
			}
		case *ast.SliceExpression:
			exprs(x.Seq)
			exprs(x.Low)
			exprs(x.High)
		case *ast.RecordLiteral:
			for _, field := range x.FieldOrder {
				exprs(field.Value)
			}
		case *ast.ArrayLiteral:
			for _, element := range x.Elements {
				exprs(element)
			}
		case *ast.VariantExpression:
			exprs(x.Payload)
		}
	}
	exprs(expr)
}
