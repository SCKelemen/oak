// ident renders an Oak name as an MSL identifier: reserved words and names
// ending in _len (which the buffer lengths use) get a suffix.
func ident(name string) string {
	if mslReserved[name] || strings.HasSuffix(name, "_len") || strings.HasPrefix(name, "oak_") {
		return name + "_"
	}
	return strings.ReplaceAll(name, ".", "__")
}
