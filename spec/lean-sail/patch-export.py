#!/usr/bin/env python3
"""Repair the Sail RISC-V Lean export where the Lean backend leaves type-level
functions untranslated (rems-project/sail#1729, open as of 2026-09-13).

Pinned to sail-riscv 0.14 generated by Sail dba5f007 (sail2, 2026-09-11):
the export's virtual-memory type synonyms `vpn_level_size`, `pte_bits`,
`ppn_bits` apply `is_sv32_mode(k_v)` in Sail syntax and never define the
type-level predicates of model/core/vmem_types.sail, so `Defs.lean` does
not parse. This script defines those predicates as Lean abbreviations,
gives the synonyms their `k_v` parameter, and rewrites the applications.
It touches nothing about instruction semantics (the definitions the
bridge in OakSailBridge/RiscV.lean imports). Idempotent; rerun after
`cmake --build build --target generated_lean_rv64d` regenerates the file.

Usage: python3 spec/lean-sail/patch-export.py [path/to/Defs.lean]
"""
import re
import sys

path = sys.argv[1] if len(sys.argv) > 1 else "external/sail-riscv/build/model/Lean_RV64D/LeanRV64D/Defs.lean"
src = open(path, encoding="utf-8").read()
marker = "-- oak-sail-bridge patch (rems-project/sail#1729)"
if marker in src:
    print("already patched:", path)
    sys.exit(0)

predicates = f"""{marker}: the type-level predicates of
-- model/core/vmem_types.sail the Lean backend does not export.
abbrev is_sv_mode (k_v : Nat) : Bool := k_v == 32 || k_v == 39 || k_v == 48 || k_v == 57
abbrev is_svx4_mode (k_v : Nat) : Bool := k_v == 34 || k_v == 41 || k_v == 50 || k_v == 59
abbrev is_sv_or_svx4_mode (k_v : Nat) : Bool := is_sv_mode k_v || is_svx4_mode k_v
abbrev is_sv32_mode (k_v : Nat) : Bool := k_v == 32 || k_v == 34

"""
n = 0
def sub(pattern, repl, count=1):
    global src, n
    src, k = re.subn(pattern, repl, src, count=count, flags=re.M)
    n += k
    if k == 0:
        print("pattern not found:", pattern, file=sys.stderr)

sub(r"^abbrev root_level : Int :=", predicates + "abbrev root_level (k_v : Nat) : Int :=")
sub(r"^abbrev vpn_level_size : Int :=", "abbrev vpn_level_size (k_v : Nat) : Int :=")
sub(r"^abbrev (pte_bits|ppn_bits) k_v :=", r"abbrev \1 (k_v : Nat) :=", count=2)
# `( f(k_v)  : Bool)` — a Sail application inside a type-level `if`.
sub(r"\( ([a-z_0-9]+)\((k_[a-z0-9]+)\) +: Bool\)", r"(\1 \2 : Bool)", count=0)
open(path, "w", encoding="utf-8").write(src)
print(f"patched {path}: {n} edits")
