// The extractor has no external-helper mapping. Extract both sources in the
// existing namespace, require the entire old extraction to be an exact prefix
// (apart from its final namespace terminator), then replace that known prefix
// with an import. No generated definition is hand-edited or silently dropped.
func TestLeanWasmBitwiseModuleExtract(t *testing.T) {
	const namespace = "Oak.WasmAssembler"
	const end = "end " + namespace + "\n"
	source := selfhostBitwiseWasmSource(t)
	full, err := New().WithSource("bitwise_wasm.oak", stdlib.Prelude+"\n"+source).
		EmitLeanRoots(namespace, topLevelNames(t, source)).Get()
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(full, "sorry") {
		t.Fatal("extraction contains sorry")
	}
	base, err := os.ReadFile(filepath.Join("..", "spec", "lean", "Oak", "WasmAssemblerExtracted.lean"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasSuffix(string(base), end) || !strings.HasSuffix(full, end) {
		t.Fatal("unexpected namespace framing; refuse to factor extraction")
	}
	prefix := strings.TrimSuffix(string(base), end)
	if !strings.HasPrefix(full, prefix) {
		t.Fatal("reachable assembler definitions differ from the existing extraction; refuse to factor")
	}
	retained := strings.TrimPrefix(full, prefix)
	if prefix+retained != full || !strings.HasPrefix(retained, "def wasm_bitwise_module.loop1 ") {
		t.Fatal("factored source failed complete reconstruction or writer boundary")
	}
	extracted := "-- Generated by TestLeanWasmBitwiseModuleExtract; do not edit.\n" +
		"-- Existing helper definitions matched byte-for-byte before import factoring.\n" +
		"import Oak.WasmAssemblerExtracted\n\n" +
		"set_option autoImplicit false\nset_option linter.unusedVariables false\n" +
		"set_option maxRecDepth 65536\nset_option maxHeartbeats 4000000\n" +
		"namespace " + namespace + "\n\n" + retained
	path := filepath.Join("..", "spec", "lean", "Oak", "WasmBitwiseModuleExtracted.lean")
	if os.Getenv("OAK_LEAN_EXTRACT_UPDATE") == "1" {
		if err := os.WriteFile(path, []byte(extracted), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(committed) != extracted {
		t.Fatal("WasmBitwiseModuleExtracted.lean is stale; regenerate with OAK_LEAN_EXTRACT_UPDATE=1")
	}
}

// Finite correspondence, not a universal module-writer refinement theorem.
// The complete output array (including the untouched suffix) is kernel checked;
// a changed helper or writer must first pass the mechanical extraction check.
func TestLeanWasmBitwiseModuleFaithful(t *testing.T) {
	TestLeanWasmBitwiseModuleExtract(t)
	lake := findLake()
	if lake == "" {
		if os.Getenv("OAK_REQUIRE_WASM_LEAN") == "1" {
			t.Fatal("OAK_REQUIRE_WASM_LEAN=1 requires lake")
		}
		t.Skip("lake unavailable; equipped lane requires extraction correspondence")
	}
	root, err := filepath.Abs(filepath.Join("..", "spec", "lean"))
	if err != nil {
		t.Fatal(err)
	}
	run := func(args ...string) {
		t.Helper()
		ctx, cancel := context.WithTimeout(t.Context(), 4*time.Minute)
		defer cancel()
		cmd := exec.CommandContext(ctx, lake, args...)
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("lake %v: %v\n%s", args, err, out)
		}
	}
	run("build", "Oak.WasmBitwiseModuleExtracted", "Oak.WasmBitwiseModuleGuards", "Oak.WasmBitwiseModuleValidation", "Oak.WasmBitwiseModuleCopy", "Oak.BitwiseModule")
	run("env", "lean", "-j1", "-M2048", "WasmBitwiseModuleCopyControls.lean")
	const preamble = "import Oak.WasmBitwiseModuleExtracted\nimport Oak.BitwiseModule\nopen Oak.WasmAssembler\nset_option maxRecDepth 65536\nset_option maxHeartbeats 4000000\n"
	var claims []string
	for _, name := range []string{"bitwise", "Mix9", "Z", strings.Repeat("A", 123), strings.Repeat("B", 124), strings.Repeat("C", 127), strings.Repeat("D", 128), strings.Repeat("E", 256)} {
		for i, symbol := range []string{"&", "|", "^"} {
			original := fmt.Sprintf("%s: (left0: u32, Right9: u32): u32 = left0 %s Right9\n", name, symbol)
			fresh, err := New().WithSource("bitwise_module.oak", original).EmitWasm().Get()
			if err != nil {
				t.Fatal(err)
			}
			for _, extra := range []int{0, 17} {
				want := append(append([]byte(nil), fresh.Bytes...), bytes.Repeat([]byte{165}, extra)...)
				claims = append(claims, fmt.Sprintf("example : wasm_bitwise_module (Array.replicate %d 165) %d %s 300 = some (%d, %s) := by decide +kernel", len(want), i+1, wasmLeanArray([]byte(name)), len(fresh.Bytes), wasmLeanArray(want)))
			}
			list := func(b []byte) string { return strings.TrimPrefix(wasmLeanArray(b), "#") }
			claims = append(claims, fmt.Sprintf("example : Oak.BitwiseModule.acceptsModule .wasm .wasmLocals [32,32] 32 .%s %s %s = true := by decide +kernel", []string{"and", "or", "xor"}[i], list([]byte(name)), list(fresh.Bytes)))
		}
	}
	for _, tc := range selfhostBitwiseWasmRefusals() {
		claims = append(claims, fmt.Sprintf("example : wasm_bitwise_module (Array.replicate %d 165) %d %s 300 = some (0, Array.replicate %d 165) := by decide +kernel", tc.capacity, tc.op, wasmLeanArray(tc.name), tc.capacity))
	}
	// Extraction fuel exhaustion is not an ordinary refusal.
	claims = append(claims, "example : wasm_bitwise_module (Array.replicate 64 165) 1 #[65] 0 = none := by decide +kernel")
	dir := t.TempDir()
	for start := 0; start < len(claims); start += 16 {
		end := min(start+16, len(claims))
		path := filepath.Join(dir, fmt.Sprintf("WasmBitwiseModuleFaithful%d.lean", start/16))
		if err := os.WriteFile(path, []byte(preamble+strings.Join(claims[start:end], "\n")+"\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		run("env", "lean", path)
		t.Logf("kernel checked complete-module claims %d–%d of %d", start+1, end, len(claims))
	}
}
