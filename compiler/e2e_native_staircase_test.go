func TestE2ENativeManySequentialConditionalsProven(t *testing.T) {
	requireArm64Host(t)
	var infos []string
	comp := New().WithSource("staircase.oak", nativeStaircaseProgram).WithNativeBodies().WithNativeAsm().WithDiagnosticSink(func(d *diagnostic.Diagnostic) {
		if d.Source == "native" {
			infos = append(infos, d.Message)
		}
	})
	_, code, abnormal := buildAndRunFrom(t, "native_staircase", comp)
	joined := strings.Join(infos, "\n")
	if abnormal || code != 42 {
		t.Fatalf("staircase: exit = (%d, abnormal=%v), want 42\n%s", code, abnormal, joined)
	}
	if !strings.Contains(joined, "asm unit staircase: proven equal to its Oak body") {
		t.Errorf("three hundred sequential conditionals must be proven on the run that merges at the joins; diagnostics:\n%s", joined)
	}
}
