// This is a deliberately narrow complete-source schema, not the general Lean
// extractor (which refuses extern calls). Every nontrivia token must match.
// The same slot description emits the Oak schema and Lean resource schedule.
func lratLifecycleSchema() (string, string) {
	slots := []struct{ name, typ, count, bytes string }{
		{"starts", "u32", "ids", "ids * u32(4)"},
		{"lengths", "u32", "ids", "ids * u32(4)"},
		{"alive", "u8", "ids", "ids"},
		{"store", "u32", "store_words", "store_words * u32(4)"},
		{"assign", "u8", "vars", "vars"},
		{"trail", "u32", "vars", "vars * u32(4)"},
	}
	var source strings.Builder
	source.WriteString(`lrat_check_allocated: (record: []u32, out: [*]u32): u32 {
 accepted: u32 = LRAT_CAPACITY
 len(out) >= u32(3) ? {
 out[u32(0)] = accepted
 out[u32(1)] = u32(0)
 out[u32(2)] = u32(0)
 ok: Bool = lrat_record_fits(record)
 ok ? {
 ids: u32 = record[u32(5)] + u32(1)
 store_words: u32 = record[u32(6)] + u32(1)
 vars: u32 = record[u32(1)] + u32(1)
 unsafe {
`)
	var allocations, owns, disowns, frees, guards []string
	for _, s := range slots {
		fmt.Fprintf(&source, "%s_raw: c.Ptr = malloc(c.Size(%s))\n", s.name, s.bytes)
		allocations = append(allocations, ".allocate ."+s.name)
		guards = append(guards, s.name+"_raw != c.null()")
	}
	source.WriteString(strings.Join(guards, " && ") + " ? {\n")
	for _, s := range slots {
		fmt.Fprintf(&source, "%s: Buffer[%s] = c.own[%s](%s_raw, %s)\n", s.name, s.typ, s.typ, s.name, s.count)
		owns = append(owns, ".own ."+s.name)
	}
	source.WriteString("accepted = lrat_check(record, span(&starts), span(&lengths), span(&alive), span(&store), span(&assign), span(&trail), out)\n")
	for i := len(slots) - 1; i >= 0; i-- {
		name := slots[i].name
		fmt.Fprintf(&source, "released_%s: c.Ptr = c.disown(%s)\n", name, name)
		disowns = append(disowns, ".disown ."+name)
	}
	source.WriteString("} | { }\n")
	for i := len(slots) - 1; i >= 0; i-- {
		name := slots[i].name
		fmt.Fprintf(&source, "free(%s_raw)\n", name)
		frees = append(frees, ".free ."+name)
	}
	source.WriteString("}\n} | { }\nout[u32(0)] = accepted\n} | { }\naccepted\n}\n")
	owned := append(append(owns, ".check"), disowns...)
	plan := "-- Generated by TestLRATLifecycleSource from the audited source schema.\n" +
		"-- A resource protocol projection, not general FFI extraction.\nimport Oak.LRATLifecycle\n\nnamespace Oak.LRATLifecycle\n\n" +
		"def allocations : List Action := [" + strings.Join(allocations, ", ") + "]\n" +
		"def ownedCall : List Action := [" + strings.Join(owned, ", ") + "]\n" +
		"def cleanup : List Action := [" + strings.Join(frees, ", ") + "]\n\n" +
		"def schedule (outFits admitted : Bool) (results : Results) : List Action :=\n" +
		"  if outFits && admitted then allocations ++ (if allPresent results then ownedCall else []) ++ cleanup else []\n\nend Oak.LRATLifecycle\n"
	return source.String(), plan
}

func lifecycleTokens(source string) []string {
	s := scanner.New(source)
	var result []string
	for {
		tok := s.NextToken()
		if tok.TokenKind == token.EOF {
			return result
		}
		if tok.TokenKind != token.TRIVIA && tok.TokenKind != token.COMMENT {
			result = append(result, fmt.Sprintf("%d:%s", tok.TokenKind, tok.Literal))
		}
	}
}

func TestLRATLifecycleSource(t *testing.T) {
	expected, plan := lratLifecycleSchema()
	actual := lratSourceRegion(t, oakCertifySource, "lrat_check_allocated:", "// write_words_file")
	// Parse both complete functions too: trivia changes must not hide a
	// changed statement/block structure behind an identical token stream.
	for _, source := range []string{actual, expected} {
		p := parser.New(scanner.New(source))
		program := p.ParseProgram()
		if len(p.Errors()) != 0 || len(program.Statements) != 1 {
			t.Fatalf("lifecycle schema must parse as exactly one function: %v", p.Errors())
		}
	}
	parseShape := func(source string) string {
		return parser.New(scanner.New(source)).ParseProgram().String()
	}
	if parseShape(actual) != parseShape(expected) {
		t.Fatal("LRAT allocating entry has different parsed control structure from the audited schema")
	}
	if !reflect.DeepEqual(lifecycleTokens(actual), lifecycleTokens(expected)) {
		t.Fatal("LRAT allocating entry diverges from complete audited resource schema; review every changed guard, call and ownership transition")
	}
	// Negative controls: the audit must notice protocol changes anywhere in
	// the wrapper, including paths outside the ownership-success branch.
	for _, mutation := range [][2]string{
		{"free(trail_raw)", "free(assign_raw)"},
		{"free(starts_raw)", ""},
		{"c.disown(trail)", "c.disown(assign)"},
		{"&& trail_raw != c.null()", ""},
		{"out[u32(0)] = accepted", "free(starts_raw)"},
		{"lrat_check(record,", "lrat_other(record,"},
	} {
		changed := strings.Replace(actual, mutation[0], mutation[1], 1)
		if changed == actual || reflect.DeepEqual(lifecycleTokens(changed), lifecycleTokens(expected)) {
			t.Fatalf("audit missed mutation %q", mutation[0])
		}
	}
	path := filepath.Join("spec", "lean", "Oak", "LRATLifecyclePlan.lean")
	if os.Getenv("OAK_LEAN_EXTRACT_UPDATE") == "1" {
		if err := os.WriteFile(path, []byte(plan), 0644); err != nil {
			t.Fatal(err)
		}
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(committed) != plan {
		t.Fatal("LRAT lifecycle plan drift; regenerate after reviewing the complete source schema")
	}
}

func TestLRATLifecycleLean(t *testing.T) {
	lake, err := exec.LookPath("lake")
	if err != nil {
		if os.Getenv("OAK_REQUIRE_LRAT_BINDING_LEAN") != "" {
			t.Fatal("lake required for lifecycle contract")
		}
		t.Skip("lake unavailable")
	}
	contract := `import Oak.LRATLifecycleSoundness
open Oak.LRATLifecycle
example (results : Results) :
    (run results (fun _ => .vacant) (schedule true true results)).map observe = some (released results) :=
  production_schedule_releases results
#print axioms Oak.LRATLifecycle.production_schedule_releases
#print axioms Oak.LRATLifecycle.refused_schedule_empty
#print axioms Oak.LRATLifecycle.checker_requires_all
`
	path := filepath.Join(t.TempDir(), "LifecycleContract.lean")
	if err := os.WriteFile(path, []byte(contract), 0600); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	for _, args := range [][]string{{"build", "Oak.LRATLifecycleSoundness"}, {"env", "lean", path}} {
		cmd := exec.CommandContext(ctx, lake, args...)
		cmd.Dir = filepath.Join("spec", "lean")
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("lifecycle proof: %v\n%s", err, out)
		}
		for _, line := range strings.Split(string(out), "\n") {
			_, axioms, found := strings.Cut(line, "depends on axioms: [")
			if !found {
				continue
			}
			for _, axiom := range strings.Split(strings.TrimSuffix(strings.TrimSpace(axioms), "]"), ",") {
				switch strings.TrimSpace(axiom) {
				case "", "propext", "Classical.choice", "Quot.sound":
				default:
					t.Fatalf("unexpected lifecycle axiom: %s", line)
				}
			}
		}
	}
}

// Exercise every subset of failed allocations on both accepted and refused
// checker executions. Identities and exact reverse release order are observed.
func TestLRATLifecycleFailureMasks(t *testing.T) {
	base := formulaBindingCases(t)[0]
	var source strings.Builder
	source.WriteString(lratAllocationExterns + oakLRATSource)
	source.WriteString(lratSourceRegion(t, oakCertifySource, "lrat_check_record:", "// write_words_file"))
	source.WriteString("main: (): i32 {\n")
	for _, refuse := range []bool{false, true} {
		record := append([]uint32(nil), base.record...)
		if refuse {
			record[len(record)-1] = 31
		} // framed record, non-live hint
		for mask := uint32(0); mask < 64; mask++ {
			source.WriteString("true ? {\n" + lratEntryWords("r", record))
			fmt.Fprintf(&source, "reset_mask(c.UInt32(%d))\nout: [4]u32 = [4]u32{99, 99, 99, 99}\n", mask)
			source.WriteString("status: u32 = lrat_check_allocated(view(&r), span(&out))\n")
			want := uint32(0)
			if refuse {
				want = 2
			}
			if mask != 0 {
				want = 7
			}
			fmt.Fprintf(&source, "assert(status == u32(%d) && out[0] == status && out[3] == 99)\n", want)
			var order uint64
			for i := 5; i >= 0; i-- {
				if mask&(1<<i) == 0 {
					order = order*16 + uint64(i+1)
				}
			}
			fmt.Fprintf(&source, "assert(u64(release_order()) == u64(%d))\n", order)
			source.WriteString("assert(u32(calls()) == 6 && u32(outstanding()) == 0 && u32(bad()) == 0)\n}\n")
		}
	}
	source.WriteString("0\n}\n")
	lratEntryRun(t, lratEntryBinary(t, source.String()), nil)
	t.Log("checked all 64 allocation-failure masks on accepted and refused records")
}
