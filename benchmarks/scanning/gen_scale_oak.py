#!/usr/bin/env python3
"""Writes scale_oak.oak: the sixteen tokens of literals.h plus generated
lowercase words, as `Big64` (64 literals) and `Big256` (256 literals)
declarations, for scan_oak_scale.c to time on input.bin beside scale.c's
C variants. Deterministic; run from this directory."""
import random
random.seed(2026)
http = ["GET ", "POST ", "PUT ", "DELETE ", "Host: ", "User-Agent", "Content-Length", "Content-Type",
        "Accept: ", "Cookie: ", "HTTP/1.1", "Connection", "Referer: ", "Location: ", "Set-Cookie", "X-Forwarded"]
def words(n):
    out, seen = [], set(http)
    while len(out) < n:
        w = "".join(random.choice("abcdefghijklmnopqrstuvwxyz") for _ in range(random.randint(4, 12)))
        if w in seen: continue
        seen.add(w); out.append(w)
    return out
def decl(name, lits):
    body = "".join("  %s,\n" % ", ".join('"%s"' % l for l in lits[i:i+4]) for i in range(0, len(lits), 4))
    return "%s: literals = {\n%s}\n" % (name, body)
src = "package main\n\n// Generated by gen_scale_oak.py: the scanning harness's sixteen tokens\n// plus generated words, as 64- and 256-literal declarations.\n\n"
src += decl("Big64", http + words(48)) + "\n" + decl("Big256", http + words(240))
src += "\nmain: (): u32 = u32(0)\n"
open("scale_oak.oak", "w").write(src)
print("wrote scale_oak.oak")
