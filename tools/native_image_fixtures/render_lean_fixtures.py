#!/usr/bin/env python3
"""Render complete current-writer images as independent kernel-checkable inputs.
Generation is not validation. No Go-decoded address/extent supplies a premise.
"""
import argparse
import json
import re
from pathlib import Path


def literal(data):
    # Lossless compression only; preserve every byte, including nonloaded data.
    chunks = []
    while data:
        count = len(data) - len(data.lstrip(b'\x00'))
        if count >= 8:
            chunks.append(f'List.replicate {count} 0')
            data = data[count:]
            continue
        end = 1
        while end < len(data) and data[end:end+8] != b'\x00'*8:
            end += 1
        chunks.append('[' + ','.join(map(str, data[:end])) + ']')
        data = data[end:]
    return '(' + ' ++ '.join(chunks) + ')' if chunks else '[]'


def expand_literal(expression):
    """Diagnostic roundtrip of the restricted emitted byte-list grammar."""
    result = bytearray()
    token = re.compile(r'\s*(?:List\.replicate (\d+) 0|\[([0-9,]*)\]|(\+\+|\(|\)))')
    at = 0
    while at < len(expression):
        match = token.match(expression, at)
        if not match:
            raise ValueError('Unexpected generated byte expression')
        count, values, punctuation = match.groups()
        if count is not None:
            result.extend(bytes(int(count)))
        elif values:
            result.extend(int(value) for value in values.split(','))
        at = match.end()
    return bytes(result)


def image_literal(data):
    if len(data) < 4096 or data[120:4096] != bytes(3976):
        raise ValueError('Current writer image has a changed header/text zero gap')
    # The complete original bytes are represented losslessly, with exact cut
    # points allowing checked list identities to avoid expanding the long gap.
    result = f'({literal(data[:120])} ++ (List.replicate 3976 0 ++ {literal(data[4096:])}))'
    if expand_literal(result) != data:
        raise ValueError('Generated expression changed complete image bytes')
    return result


def conjunct(root, index, count):
    return root + '.2' * index + ('.1' if index + 1 < count else '')


def layout(index):
    return conjunct('h.2.2.2.2', index, 12)


def mutation_projection(mutation):
    name, family = mutation['name'], mutation['family']
    if family == 'header':
        if name.startswith('header_ident_'):
            return conjunct('h.1.1', 1, 11)
        field = name.removeprefix('header_')
        base = {'type':2, 'machine':3, 'version':4, 'phoff':5, 'flags':6,
                'ehsize':7, 'phentsize':8, 'phnum':9}
        return (conjunct('h.1.1', base[field], 11) if field in base else
                conjunct('h.1', {'entry':1,'shoff':2,'shentsize':3,'shnum':4,'shstrndx':5}[field], 6))
    if name.startswith('program_') or family == 'abi':
        if family == 'abi': return conjunct('h.1.1', 6, 11)
        if name == 'program_type': return conjunct('h.1.1', 10, 11)
        return 'h.2.1.2' if name == 'program_paddr' else 'h.2.1.1'
    if name.startswith('section_') and name.split('_')[1].isdigit():
        return conjunct('h.2.2.1', int(name.split('_')[1]), 6)
    if name.startswith('symbol_') and name.split('_')[1].isdigit():
        return conjunct('h.2.2.2.1', int(name.split('_')[1]), 6)
    if name.startswith('function_'): return conjunct('h.2.2.2.1', 2, 6)
    if name == 'text_offset_overlap_header': return conjunct('h.2.2.1', 1, 6)
    if name.startswith('symtab_'): return conjunct('h.2.2.1', 3, 6)
    if name.startswith('rodata_'): return conjunct('h.2.2.1', 2, 6)
    if family == 'body': return None
    if family == 'header_padding':
        return f'congrArg (fun xs : Bytes => xs.getD {mutation["offset"] - 120} 0) ({layout(5)})'
    return layout({'name':8, 'section_names':9, 'stub':6, 'text_padding':7,
                   'section_padding':10, 'truncation':2, 'append':2}[family])


SUPPORT = r"""
private theorem slice_after (pre suffix : Bytes) (offset count : Nat)
    (bound : pre.length ≤ offset) :
    slice (pre ++ suffix) offset count = slice suffix (offset-pre.length) count := by
  unfold slice
  rw [List.drop_append, List.drop_eq_nil_of_le bound, List.nil_append]

private theorem padded_tail_slice (header suffix : Bytes) (hlen : header.length = 120)
    (offset count : Nat) (bound : 4096 ≤ offset) :
    slice (header ++ (List.replicate 3976 0 ++ suffix)) offset count =
      slice suffix (offset-4096) count := by
  have plen : (header ++ List.replicate 3976 (0 : BitVec 8)).length = 4096 := by
    rw [List.length_append, hlen, List.length_replicate]
  rw [← List.append_assoc]
  have hbound : (header ++ List.replicate 3976 (0 : BitVec 8)).length ≤ offset := by
    rw [plen]
    exact bound
  simpa only [plen] using slice_after (header ++ List.replicate 3976 0) suffix offset count hbound

private theorem padded_tail_read (header suffix : Bytes) (hlen : header.length = 120)
    (offset count : Nat) (bound : 4096 ≤ offset) :
    readLE (header ++ (List.replicate 3976 0 ++ suffix)) offset count =
      readLE suffix (offset-4096) count := by
  unfold readLE
  rw [padded_tail_slice header suffix hlen offset count bound]
private theorem zero_gap (header tail : Bytes) (length : header.length = 120) :
    Oak.MinimalELF.slice (header ++ (List.replicate 3976 0 ++ tail)) 120 3976 = List.replicate 3976 0 := by
  unfold Oak.MinimalELF.slice
  rw [List.drop_left' length]
  exact List.take_left' List.length_replicate

private theorem accepts_of_profile {m : Oak.MinimalELF.Machine} {name image expectedBody : Bytes}
    (profile : StrictProfile m name image)
    (body : Oak.MinimalELF.slice image (bodyOffset m) (bodySize m) = expectedBody) :
    accepts m name image expectedBody = true := by
  simp only [accepts,extract,if_pos profile,profile_decodes profile,candidate,decide_eq_true_eq]
  exact body

private theorem refuses_profile {m : Oak.MinimalELF.Machine} {name image expectedBody : Bytes}
    {condition : Prop} (necessary : StrictProfile m name image → condition)
    (bad : ¬ condition) : accepts m name image expectedBody = false := by
  have absent : ¬ StrictProfile m name image := fun h => bad (necessary h)
  simp only [accepts, extract, if_neg absent]

private theorem refuses_body {m : Oak.MinimalELF.Machine} {name image expectedBody : Bytes}
    (bad : Oak.MinimalELF.slice image (bodyOffset m) (bodySize m) ≠ expectedBody) :
    accepts m name image expectedBody = false := by
  cases h : accepts m name image expectedBody with
  | false => rfl
  | true =>
    obtain ⟨l, _, _, _, _, _, _, offset, size, _, body, _, _, _, _⟩ := accepted_named_load h
    rw [offset, size] at body
    exact False.elim (bad body.symm)

private theorem load_of_accepts {m : Oak.MinimalELF.Machine} {name image expectedBody : Bytes}
    (h : accepts m name image expectedBody = true) :
    (extract m name image).bind (fun loaded => Oak.MinimalELF.loadBytes image loaded.address loaded.size) = some expectedBody := by
  obtain ⟨l, extracted, _, _, _, _, _, _, _, _, _, _, loaded, _, _⟩ := accepted_named_load h
  rw [extracted]
  exact loaded
"""

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--output', type=Path, default=Path('spec/lean/NativeBitwiseImageFixtures.lean'))
    parser.add_argument('--fresh', action='store_true', help='Core current-emission controls; omit large fixed mutation matrix')
    args = parser.parse_args()
    manifest = json.loads((args.directory / 'manifest.json').read_text())
    out = ['import Oak.NativeBitwiseImage', '', '/-!',
           '# Complete production native executable fixtures', '',
           'Each complete image is an actual unchanged asm.WriteExecutable result,',
           'using the original source object body as an untrusted writer input.',
           'The whole ELF file is passed to Lean, including nonloaded metadata.',
           'Final names, addresses, extents and loader bytes are decoded by Lean.',
           'No source execution, startup, external ISA, OS or production authority',
           'claim follows from this finite diagnostic evidence.', '-/',
           'set_option autoImplicit false', 'set_option linter.unusedSimpArgs false', 'set_option maxRecDepth 16384',
           'set_option maxHeartbeats 3200000',
           'namespace Oak.NativeBitwiseImageFixtures',
           'open Oak.NativeBitwiseImage', 'open Oak.NativeBitwiseObject (fromUInt8)',
           'open Oak.MinimalELF (Bytes readLE slice)', '',
           'def setLE (image : Bytes) (offset width value : Nat) : Bytes :=',
           '  (List.range width).foldl (fun bytes i =>',
           '    bytes.set (offset + i) (BitVec.ofNat 8 (value / 256^i % 256))) image', '']
    out.extend(SUPPORT.splitlines())
    counts = {'admissions': 0, 'loads': 0, 'refusals': 0}
    for fixture in manifest['fixtures']:
        ident = fixture['id']
        machine = '.rv64' if fixture['target'] == 'linux/riscv64' else '.arm64'
        other_machine = '.arm64' if machine == '.rv64' else '.rv64'
        def body(op):
            if machine == '.rv64':
                return f'(RiscVFramedBitwise.functionBytes .{op})'
            return f'(fromUInt8 (AArch64BitwiseFunction.functionBytes .{op}))'
        expected = body(fixture['operation'])
        raw = (args.directory / fixture['image_path']).read_bytes()
        image_literal(raw)  # Validate the exact zero gap before its lossless representation.
        source = (args.directory / fixture['source_path']).read_bytes()
        out.extend([f'namespace {ident}',
                    f'def source : List UInt8 := {literal(source)}',
                    f'def nameBytes : Bytes := {literal(fixture["function"].encode())}',
                    f'def header : Bytes := {literal(raw[:120])}',
                    f'def suffix : Bytes := {literal(raw[4096:])}',
                    'def image : Bytes := header ++ (List.replicate 3976 0 ++ suffix)'])
        out.extend([
            'private theorem header_length : header.length = 120 := by decide +kernel',
            f'private theorem image_length : image.length = {len(raw)} := by',
            f'  change (header ++ (List.replicate 3976 0 ++ suffix)).length = {len(raw)}',
            '  rw [List.length_append, List.length_append, List.length_replicate, header_length]',
            '  decide +kernel',
            f'private theorem h40 : readLE image 40 8 = {int.from_bytes(raw[40:48], "little")} := by decide +kernel',
            'private theorem h58 : readLE image 58 2 = 64 := by decide +kernel',
            'private theorem h60 : readLE image 60 2 = 6 := by decide +kernel',
            'private theorem read_tail (offset count : Nat) (bound : 4096 ≤ offset) :',
            '    readLE image offset count = readLE suffix (offset-4096) count :=',
            '  padded_tail_read header suffix header_length offset count bound',
            'private theorem slice_tail (offset count : Nat) (bound : 4096 ≤ offset) :',
            '    slice image offset count = slice suffix (offset-4096) count :=',
            '  padded_tail_slice header suffix header_length offset count bound'])
        def refuse(label, image='image', name='nameBytes', target=machine, code=expected, projection=None, body=False):
            if body:
                proof = 'by apply refuses_body; decide +kernel'
            else:
                if projection is None:
                    projection = ({'overlong_name':layout(11), 'wrong_target':conjunct('h.1.1',3,11),
                                   'wrong_name':layout(8), 'empty_name':layout(0), 'nul_name':layout(1),
                                   'non_ascii_name':layout(1), 'body_only_image':conjunct('h.1.1',0,11),
                                   'complete_name_replay':layout(8)}.get(label, layout(2)))
                proof = f'by apply refuses_profile (fun h => {projection}); decide +kernel'
            out.append(f'theorem reject_{label} : accepts {target} {name} {image} {code} = false := {proof}')
            counts['refusals'] += 1
        if len(fixture['function']) > 256:
            refuse('overlong_name')
        else:
            atom = '(by (try simp only [Oak.NativeBitwiseObject.readSection, Oak.NativeBitwiseObject.readSymbol, Oak.NativeBitwiseObject.symbolName, Oak.MinimalELF.segment, textSection, dataSection, symSection, strSection, shstrSection, functionSymbol, startSymbol, nullSection, nullSymbol, image_length, h40, h58, h60]); (try simp (disch := decide) only [read_tail, slice_tail]); all_goals decide +kernel)'
            def pair(parts): return '⟨' + ','.join(parts) + '⟩'
            layout_atoms = [atom] * 12
            layout_atoms[5] = '(zero_gap header suffix header_length)'
            profile = pair([pair([pair([atom]*11)] + [atom]*5), pair([atom]*2),
                            pair([atom]*6), pair([atom]*6), pair(layout_atoms)])
            out.append(f'theorem admitted : accepts {machine} nameBytes image {expected} = true := by exact accepts_of_profile {profile} {atom}')
            out.append(f'theorem loaded : (extract {machine} nameBytes image).bind (fun loaded => Oak.MinimalELF.loadBytes image loaded.address loaded.size) = some {expected} := by exact load_of_accepts admitted')
            counts['admissions'] += 1
            counts['loads'] += 1
            refuse('wrong_target', target=other_machine)
            refuse('wrong_name', name='[122,122]')
            refuse('empty_name', name='[]')
            refuse('nul_name', name='(nameBytes ++ [0])')
            refuse('non_ascii_name', name='[128]')
            refuse('wrong_op', code=body('or' if fixture['operation'] == 'and' else 'and'), body=True)
            refuse('wrong_body_extent', code=f'({expected} ++ [0])', body=True)
            refuse('body_only_image', image=expected)
            refuse('append_zero', image='(image ++ [0])')
            refuse('truncate_last', image='(image.take (image.length - 1))')
        if not args.fresh and ident in ('arm64_mix_and', 'riscv64_mix_and'):
            for mutation in fixture['mutations']:
                kind, off, value = mutation['kind'], mutation['offset'], mutation.get('value', 0)
                if kind == 'set_le':
                    expression = f'(setLE image {off} {mutation["width"]} {value})'
                elif kind == 'xor_byte':
                    expression = f'(image.set {off} ((image.getD {off} 0) ^^^ (BitVec.ofNat 8 {value})))'
                elif kind == 'truncate':
                    expression = f'(image.take {off})'
                elif kind == 'append_byte':
                    expression = f'(image ++ [{value}])'
                else:
                    raise ValueError(kind)
                refuse('mutation_' + mutation['name'], image=expression, projection=mutation_projection(mutation), body=mutation['family']=='body')
            # MinimalELF alone may accept omitted metadata; the strict checker cannot.
            load_end = 4160 if machine == '.rv64' else 4128
            refuse('loaded_segment_only', image=f'(image.take {load_end})')
            refuse('oversized_5121', image='(image ++ List.replicate (5121 - image.length) 0)')
            # Change both actual name strings consistently to the other valid name.
            # Retain requested source name, so valid-image name replay is rejected.
            alternate = next(f for f in manifest['fixtures'] if f['id'] == ident.replace('_mix_', '_Mix9_'))
            out.append(f'def renamedImage : Bytes := {image_literal((args.directory / alternate["image_path"]).read_bytes())}')
            refuse('complete_name_replay', image='renamedImage')
        out.extend([f'end {ident}', ''])
    out.extend(['end Oak.NativeBitwiseImageFixtures', ''])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(out))
    counts['total'] = sum(counts.values())
    counts['compiled'] = False
    print(json.dumps(counts))
    (args.directory / ('fresh-counts.json' if args.fresh else 'lean-fixture-counts.json')).write_text(json.dumps(counts, indent=2)+'\n')


if __name__ == '__main__':
    main()
